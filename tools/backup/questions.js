/* عدد الأسئلة المتاحة في كل فئة */
const questionsCount = Object.keys(questionsData).reduce((acc, cat) => {
  acc[cat] = questionsData[cat].length;
  return acc;
}, {});

/* قيم النقاط الخمس ومستوياتها */
const POINT_LEVELS = { 100: 1, 200: 2, 300: 3, 400: 4, 500: 5 };

/* يبني أسئلة جولة واحدة: سؤال عشوائي من كل مستوى لكل فئة مختارة */
function buildRoundQuestions(categoryTitles) {
  const round = {};
  (categoryTitles || []).forEach(cat => {
    const pool = questionsData[cat] || [];
    Object.keys(POINT_LEVELS).forEach(points => {
      const level = POINT_LEVELS[points];
      let candidates = pool.filter(item => item.l === level);
      if (!candidates.length) candidates = pool;           // احتياط
      if (!candidates.length) return;
      const picked = candidates[Math.floor(Math.random() * candidates.length)];
      round[cat + "_" + points] = picked;
    });
  });
  return round;
}

if (typeof window !== "undefined") {
  window.questionsData  = questionsData;
  window.questionsCount = questionsCount;
  window.buildRoundQuestions = buildRoundQuestions;
}
